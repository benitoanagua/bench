/**
 * IBM Plex self-hosting generator (bench-design-system.md §2.7, decisiones
 * cerradas 1-3: preferir variable font, autohospedado, font-display swap con
 * fallback dimensionado).
 *
 * Copies the `.woff2` builds of IBM Plex Sans and IBM Plex Mono from the
 * official `@ibm/plex-sans` / `@ibm/plex-mono` npm packages into
 * `packages/fonts/dist/` and writes `fonts.css` with `@font-face` rules.
 *
 * Publishes, in order of preference, per family:
 *   1. The variable build (`*Var*.woff2`) — one file, full weight range —
 *      matching spec decision 1, whenever the official package carries one.
 *   2. Otherwise the two static builds Bench actually uses (Regular 400 and
 *      SemiBold 600, §2.7 "pesos — dos, no tres"). The official npm packages
 *      publish static builds only today; preferring a hard-to-verify variable
 *      file would violate the "assets as the official package delivers them"
 *      rule. If a later release ships variable files, this script picks them
 *      up automatically and the static subset becomes dead weight.
 *
 * Never a CDN at runtime: the consuming app includes `packages/fonts/` output
 * as a local asset. This script runs only at build time.
 *
 *   pnpm fonts:build
 */
import { existsSync, mkdirSync, copyFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const outDir = join(root, 'packages', 'fonts', 'dist');
mkdirSync(outDir, { recursive: true });

/** Resolve an npm package dir: root node_modules link first, then the pnpm store. */
function resolvePackageDir(name) {
  const hoisted = join(root, 'node_modules', name);
  if (existsSync(join(hoisted, 'package.json'))) return hoisted;
  const base = join(root, 'node_modules', '.pnpm');
  if (!existsSync(base)) throw new Error(`pnpm store not found at ${base} — run pnpm install`);
  // pnpm encodes scope slashes as '+' in .pnpm store dir names: @ibm/plex-sans → @ibm+plex-sans@x.y.z
  const encoded = `${name.replace('@', '').replace('/', '+')}@`;
  const dir = readdirSync(base)
    .filter((d) => d.startsWith(encoded))
    .map((d) => join(base, d, 'node_modules', name))
    .filter((d) => existsSync(join(d, 'package.json')));
  return dir[0] ?? null;
}

const families = [
  { pkg: '@ibm/plex-sans', family: 'IBM Plex Sans' },
  { pkg: '@ibm/plex-mono', family: 'IBM Plex Mono' },
];

let css = `/*
 * IBM Plex self-hosted fonts — generated by tooling/typography/build.mjs at
 * build time. Source of truth: the official @ibm/plex-sans and @ibm/plex-mono
 * npm packages (Apache-2.0). Never a third-party CDN at runtime (§2.8 §2.7).
 * The dimensioned 'IBM Plex Sans Fallback' stack lives in @bench/components'
 * styles/global.css.
 */
@font-face {
  font-family: 'IBM Plex Sans Fallback';
  src: local('Arial'), local('Helvetica Neue');
  ascent-override: 92%;
  descent-override: 23%;
  size-adjust: 105%;
  font-display: swap;
}
@font-face {
  font-family: 'IBM Plex Mono Fallback';
  src: local('Consolas'), local('Menlo'), local('Courier New');
  ascent-override: 100%;
  descent-override: 22%;
  size-adjust: 100%;
  font-display: swap;
}
`;

let copied = 0;
for (const { pkg, family } of families) {
  const dir = resolvePackageDir(pkg);
  if (!dir) throw new Error(`${pkg} not found — add it as a devDependency and run pnpm install`);
  const woff2Dir = join(dir, 'fonts', 'complete', 'woff2');
  if (!existsSync(woff2Dir)) throw new Error(`No fonts/complete/woff2/ in ${dir}`);

  const files = readdirSync(woff2Dir).filter((f) => f.endsWith('.woff2') && !/Italic/i.test(f));
  const variable = files.filter((f) => /Var/i.test(f));
  const scoped = (names) =>
    names.map((n) => files.find((f) => f.replace(/\.woff2$/, '').endsWith(n))).filter(Boolean);
  const priorities = variable.length > 0 ? variable : scoped(['Regular', 'SemiBold']);

  for (const file of priorities) {
    const src = join(woff2Dir, file);
    if (!existsSync(src)) continue;
    copyFileSync(src, join(outDir, file));
    const isVar = /Var/i.test(file);
    const weight = isVar ? '100 700' : file.includes('SemiBold') ? 600 : 400;
    css += `
@font-face {
  font-family: '${family}';
  src: url('./${file}') format('woff2'${isVar ? '-variations' : ''});
  font-weight: ${weight};
  font-style: normal;
  font-display: swap;
}
`;
    copied += 1;
  }
}

if (copied === 0)
  throw new Error('No .woff2 fonts copied — inspect the @ibm/plex-* package layout');
for (const family of ['IBM Plex Sans', 'IBM Plex Mono']) {
  if (!css.includes(`'${family}';`)) {
    // quality gate: each Bench family must end up with at least one @font-face
    throw new Error(`Missing @font-face for ${family}`);
  }
}

writeFileSync(join(outDir, 'fonts.css'), css);
console.log(`✓ ${copied} font file(s) → packages/fonts/dist (fonts.css + woff2)`);
